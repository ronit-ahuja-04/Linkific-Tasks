import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import teardown from '../e2e/teardown';
import { dbFault, LABEL, RESULTS, ROOT, type Observation } from './record';

/**
 * After the scenarios: write docs/errors/<label>.md from what was recorded, then delete the throwaway accounts.
 * The table is facts only (status, what is on screen, stuck or not, errors); the judgement is in docs/ERROR_INVENTORY.md.
 */
const cell = (value: unknown): string => String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export default async function report(): Promise<void> {
  await dbFault('pass').catch(() => undefined);
  teardown();
  if (!existsSync(RESULTS)) return;
  const rows = readFileSync(RESULTS, 'utf8').trim().split('\n').filter(Boolean).map((line) => JSON.parse(line) as Observation);
  rows.sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));

  // the server log: each error starts with "⨯"; a page error is followed a few lines later by its digest
  const serverLog = path.join(ROOT, 'inventory', '.server.log');
  const log = existsSync(serverLog) ? readFileSync(serverLog, 'utf8').replace(/\x1b\[[0-9;]*m/g, '').split('\n') : [];
  const serverErrors = log.flatMap((line, i) => {
    if (!line.startsWith('⨯')) return [];
    const digest = log.slice(i + 1, i + 10).find((l) => l.includes('digest:'))?.match(/digest: '(\w+)'/)?.[1];
    return [`${line.slice(0, 150)}${digest ? `   (digest ${digest})` : '   (no digest)'}`];
  });
  const noise = rows.reduce((sum, r) => sum + (r.noise ?? 0), 0);

  const lines = [
    `# Error inventory: ${LABEL}`,
    '',
    `Generated by \`npm run inventory\` (label \`${LABEL}\`) on ${new Date().toISOString().slice(0, 10)}, against a production build (\`next build\` + \`next start\`).`,
    'Each row causes one failure and records what a person would see. Faults come from the browser (Playwright: offline, hung or rewritten requests) or from the database (`inventory/fault-proxy.mjs` between the app and Supabase).',
    '',
    '**Stuck** = the action\'s button is still disabled, or still says it is working, when we stop waiting. **Errors** = console errors / uncaught exceptions in the page.',
    `Not counted: ${noise} console errors from the \`/_vercel/*\` analytics scripts, which exist only on Vercel (two per page locally).`,
    '',
    '| # | Area | Operation | Fault | Status | What the user sees | Stuck | Errors | Notes | Screen |',
    '|---|---|---|---|---|---|---|---|---|---|',
    ...rows.map((r) => {
      const status = r.status ? `${r.status}${r.contentType ? ` ${r.contentType.split(';')[0]}` : ''}` : '';
      const stuck = r.stuck === undefined ? '' : r.stuck ? `**yes**${r.ms ? ` (${r.ms / 1000} s)` : ''}` : 'no';
      const errors = [...r.pageErrors.map((e) => `uncaught: ${e}`), ...r.console.map((e) => `console: ${e}`)];
      const errorCell = errors.length === 0 ? '' : `${errors.length}: ${cell(errors.slice(0, 2).join(' / '))}`;
      const notes = [r.note, r.ms && r.stuck === undefined ? `${r.ms} ms` : ''].filter(Boolean).join('; ');
      return `| ${r.id} | ${cell(r.area)} | ${cell(r.operation)} | ${cell(r.fault)} | ${cell(status)} | ${cell(r.sees)} | ${stuck} | ${errorCell} | ${cell(notes)} | ${r.screenshot ? `[view](${r.screenshot})` : ''} |`;
    }),
    '',
    `## What the server logged (${serverErrors.length} errors)`,
    '',
    'The first line of each error, and the digest Next.js showed the user for it (API errors have none).',
    '',
    '```text',
    ...serverErrors.slice(0, 30),
    '```',
    '',
  ];
  writeFileSync(path.join(ROOT, 'docs', 'errors', `${LABEL}.md`), lines.join('\n'));
}
