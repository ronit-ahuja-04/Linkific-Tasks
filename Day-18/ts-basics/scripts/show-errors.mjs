// Proves the `// @ts-expect-error` lines really are errors, and writes down what the compiler says.
//
// For every test file it copies the file into .tmp-errors/, blanks each `// @ts-expect-error` comment
// (so the line beneath is checked normally), runs `tsc` on the copy, and matches each compiler message to
// the explanation written next to the directive. The result is compile-errors.md.
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const TMP = '.tmp-errors';
rmSync(TMP, { recursive: true, force: true });
mkdirSync(join(TMP, 'test'), { recursive: true });
cpSync('src', join(TMP, 'src'), { recursive: true });
writeFileSync(
  join(TMP, 'tsconfig.json'),
  JSON.stringify({ extends: '../tsconfig.json', compilerOptions: { noUnusedLocals: false, noUnusedParameters: false }, include: ['src', 'test'] }),
);

// explanations[file][lineNumber] = text written after the directive
const explanations = {};
for (const name of readdirSync('test').filter((f) => /\.test\.tsx?$/.test(f))) {
  const lines = readFileSync(join('test', name), 'utf8').split('\n');
  explanations[name] = {};
  const out = lines.map((line, i) => {
    const match = line.match(/\/\/ @ts-expect-error\s*(.*)$/);
    if (!match) return line;
    explanations[name][i + 2] = (match[1] ?? '').trim(); // the directive applies to the NEXT line (1-based: i + 2)
    return line.replace(/\/\/ @ts-expect-error.*$/, '');
  });
  writeFileSync(join(TMP, 'test', name), out.join('\n'));
}

let output = '';
const debug = process.env.DEBUG_ERRORS === '1';
try {
  execFileSync('npx', ['tsc', '--noEmit', '-p', TMP, '--pretty', 'false'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
} catch (error) {
  output = String(error.stdout ?? '') + String(error.stderr ?? '');
}
if (debug) console.log(output.slice(0, 1500));

const rows = [];
const seen = new Set(); // one row per marked line, even when the compiler reports two errors on it
let unexplained = 0;
for (const line of output.split('\n')) {
  const m = line.match(/^\.tmp-errors\/test\/([^(]+)\((\d+),\d+\): error (TS\d+): (.*)$/);
  if (!m) continue;
  const [, file, lineNo, code, message] = m;
  const why = explanations[file]?.[Number(lineNo)];
  if (why === undefined) { unexplained += 1; continue; }
  if (seen.has(`${file}:${lineNo}`)) continue;
  seen.add(`${file}:${lineNo}`);
  rows.push({ file, why, code, message: message.split('\n')[0] });
}

const total = Object.values(explanations).reduce((n, byLine) => n + Object.keys(byLine).length, 0);
let md = '# Mistakes the compiler caught\n\n';
md += 'Generated by `npm run errors`. Each row is a line from the tests that is marked `// @ts-expect-error`: the script removes the marker, runs the TypeScript compiler on it, and records what it says. Nothing here is written by hand.\n\n';
md += `${rows.length} of ${total} marked lines produced a compiler error.\n\n`;
md += '| Test file | What is wrong | Compiler says |\n| --- | --- | --- |\n';
for (const r of rows) md += `| \`${r.file}\` | ${r.why} | \`${r.code}\`: ${r.message.replace(/\|/g, '\\|')} |\n`;
writeFileSync('compile-errors.md', md);
rmSync(TMP, { recursive: true, force: true });
console.log(`${rows.length} of ${total} marked lines are compile errors (${unexplained} other errors not matched).`);
if (rows.length !== total) process.exit(1);
