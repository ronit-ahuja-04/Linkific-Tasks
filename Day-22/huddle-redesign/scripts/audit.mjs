// The manual-accessibility measurements axe does not make, page by page, as a Markdown report.
// Run before and after the redesign (same database seed, dev server on :5177):
//   node scripts/audit.mjs before    -> docs/audit/before.md
//   node scripts/audit.mjs after     -> docs/audit/after.md
import { mkdirSync, writeFileSync } from 'node:fs';
import AxeBuilder from '@axe-core/playwright';
import { chromium } from '@playwright/test';

const label = process.argv[2] ?? 'report';
const BASE = process.env.BASE_URL ?? 'http://localhost:5177';
const PAGES = [
  { name: 'Sign in', path: '/login', signedIn: false },
  { name: 'Dashboard', path: '/' },
  { name: 'Chat (room)', path: '/chat', room: 'General' },
  { name: 'Notes', path: '/notes' },
  { name: 'Files', path: '/files' },
  { name: 'Profile', path: '/profile' },
  { name: 'Query lab', path: '/lab' },
];
const TABS = 40;

const browser = await chromium.launch({ channel: 'chrome' });
const signedOut = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const signedIn = await browser.newContext({ viewport: { width: 1440, height: 900 } });
{
  const page = await signedIn.newPage();
  await page.goto(`${BASE}/login`);
  await page.getByLabel('Email').first().fill('ada@example.com');
  await page.getByLabel('Password', { exact: true }).first().fill('demo-password-123');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL(`${BASE}/`);
  await page.close();
}

async function open(page, { path, room }) {
  await page.goto(`${BASE}${path}`);
  if (room) {
    await page.getByRole('link', { name: room }).first().click();
    await page.waitForURL(/\/chat\/.+/);
  }
  await page.waitForLoadState('networkidle');
  await page.waitForTimeout(600);
}

/** Press Tab repeatedly; for each stop record what it is and whether focus is VISIBLY different from no focus */
async function tabWalk(page) {
  await page.evaluate(() => (document.activeElement instanceof HTMLElement ? document.activeElement.blur() : undefined));
  const stops = [];
  for (let i = 0; i < TABS; i += 1) {
    await page.keyboard.press('Tab');
    const info = await page.evaluate(() => {
      const el = document.activeElement;
      if (!el || el === document.body) return null;
      const name = (el.getAttribute('aria-label') || el.textContent || el.getAttribute('placeholder') || el.getAttribute('title') || '').trim().replace(/\s+/g, ' ').slice(0, 40);
      const focused = getComputedStyle(el);
      const ring = `${focused.outlineStyle} ${focused.outlineWidth} ${focused.boxShadow}`;
      const inMain = Boolean(el.closest('main'));
      const rect = el.getBoundingClientRect();
      return { tag: el.tagName.toLowerCase(), role: el.getAttribute('role'), name, ring, inMain, w: Math.round(rect.width), h: Math.round(rect.height), visible: rect.width > 0 && rect.height > 0 };
    });
    if (!info) break;
    // compare with the same element unfocused
    const plain = await page.evaluate(() => {
      const el = document.activeElement;
      if (!(el instanceof HTMLElement)) return '';
      el.blur();
      const s = getComputedStyle(el);
      const ring = `${s.outlineStyle} ${s.outlineWidth} ${s.boxShadow}`;
      el.focus({ focusVisible: true });
      return ring;
    });
    stops.push({ ...info, focusVisible: info.ring !== plain && !/^none 0px none$/.test(info.ring) });
    if (stops.length > 2 && stops[0].name === info.name && stops[0].tag === info.tag) break; // wrapped around
  }
  return stops;
}

const lines = [`# Accessibility measurements: ${label}`, '', `Generated by \`node scripts/audit.mjs ${label}\` against ${BASE}. Desktop 1440×900 unless stated.`, ''];
for (const target of PAGES) {
  const page = await (target.signedIn === false ? signedOut : signedIn).newPage();
  await open(page, target);
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze();
  const structure = await page.evaluate(() => ({
    landmarks: [...document.querySelectorAll('header, nav, main, aside, footer, [role=banner], [role=navigation], [role=main], [role=complementary], [role=contentinfo], [role=search], [role=region][aria-label], section[aria-label], section[aria-labelledby]')]
      .map((el) => `${el.getAttribute('role') || el.tagName.toLowerCase()}${el.getAttribute('aria-label') ? ` "${el.getAttribute('aria-label')}"` : ''}`),
    headings: [...document.querySelectorAll('h1, h2, h3, h4, h5, h6')].map((h) => `${h.tagName.toLowerCase()} ${h.textContent.trim().replace(/\s+/g, ' ').slice(0, 50)}`),
    live: [...document.querySelectorAll('[aria-live], [role=status], [role=alert], [role=log]')].map((el) => `${el.getAttribute('role') || 'aria-live=' + el.getAttribute('aria-live')}`),
    imagesWithoutAlt: document.querySelectorAll('img:not([alt])').length,
    skipLink: [...document.querySelectorAll('a[href^="#"]')].some((a) => /skip/i.test(a.textContent)),
    reducedMotionCss: [...document.styleSheets].some((sheet) => { try { return [...sheet.cssRules].some((r) => r.cssText.includes('prefers-reduced-motion')); } catch { return false; } }),
  }));
  const stops = await tabWalk(page);
  const firstInMain = stops.findIndex((s) => s.inMain);
  const noRing = stops.filter((s) => !s.focusVisible);
  await page.setViewportSize({ width: 320, height: 640 });
  await page.waitForTimeout(300);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);
  const smallTargets = await page.evaluate(() => [...document.querySelectorAll('a, button, input, select, textarea, [tabindex="0"]')]
    .filter((el) => { const r = el.getBoundingClientRect(); return r.width > 0 && r.height > 0 && (r.width < 24 || r.height < 24) && !(el.tagName === 'A' && el.closest('p, li')) && !el.closest('[aria-hidden="true"]'); }) // (M5: hidden from assistive tech and not focusable = not a target)
    .map((el) => `${el.tagName.toLowerCase()} "${(el.getAttribute('aria-label') || el.textContent || '').trim().slice(0, 24)}" ${Math.round(el.getBoundingClientRect().width)}×${Math.round(el.getBoundingClientRect().height)}`));

  lines.push(`## ${target.name} (\`${target.path}\`)`, '');
  lines.push(`| Check | Result |`, `|---|---|`);
  lines.push(`| axe (WCAG 2.2 AA) | ${axe.violations.length === 0 ? 'no violations' : axe.violations.map((v) => `${v.id} ×${v.nodes.length}`).join(', ')} |`);
  lines.push(`| Skip link | ${structure.skipLink ? 'yes' : '**no**'} |`);
  lines.push(`| Tab stops before the main content | ${firstInMain === -1 ? `none reached in ${stops.length}` : firstInMain} |`);
  lines.push(`| Tab stops with no visible focus change | ${noRing.length === 0 ? 'none' : `**${noRing.length}**: ${noRing.slice(0, 6).map((s) => `${s.tag} "${s.name}"`).join('; ')}`} |`);
  lines.push(`| Landmarks | ${structure.landmarks.join(', ') || '**none**'} |`);
  lines.push(`| Headings | ${structure.headings.join(' · ') || '**none**'} |`);
  lines.push(`| Live regions | ${structure.live.join(', ') || 'none'} |`);
  lines.push(`| Images without alt | ${structure.imagesWithoutAlt} |`);
  lines.push(`| Horizontal overflow at 320 px | ${overflow > 0 ? `**${overflow}px**` : 'none'} |`);
  lines.push(`| Targets under 24×24 px at 320 px (WCAG 2.5.8) | ${smallTargets.length === 0 ? 'none' : `**${smallTargets.length}**: ${smallTargets.slice(0, 5).join('; ')}`} |`);
  lines.push(`| \`prefers-reduced-motion\` in the CSS | ${structure.reducedMotionCss ? 'yes' : 'no'} |`);
  lines.push('', `<details><summary>Tab order (${stops.length} stops)</summary>`, '', stops.map((s, i) => `${i + 1}. ${s.tag}${s.role ? `[${s.role}]` : ''} "${s.name}"${s.focusVisible ? '' : ' (no visible focus)'}${s.inMain ? '' : ' (outside main)'}`).join('\n'), '', '</details>', '');
  await page.close();
}
await browser.close();
mkdirSync('docs/audit', { recursive: true });
writeFileSync(`docs/audit/${label}.md`, lines.join('\n'));
console.log(`docs/audit/${label}.md`);
