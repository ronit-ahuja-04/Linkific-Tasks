/**
 * Contrast check for the design tokens: reads src/styles/tokens.css, resolves every var() for the light and
 * the dark theme, scores each pair in CONTRAST_PAIRS against WCAG 2.2 AA, writes docs/contrast.md and
 * exits 1 if any pair fails.
 *
 *   npm run contrast
 *
 * The unit test (test/design-tokens.test.js) imports the same functions, so `npm test` fails on a bad token too.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CONTRAST_PAIRS, contrastRatio, formatRatio } from '../src/lib/contrast.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const TOKENS_FILE = resolve(ROOT, 'src/styles/tokens.css');

/** Top-level rule blocks of a stylesheet ({selector, body}); @media and other at-rules are skipped */
function topLevelRules(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const rules = [];
  let depth = 0;
  let start = 0;
  let selector = '';
  for (let i = 0; i < text.length; i += 1) {
    if (text[i] === '{') {
      if (depth === 0) {
        selector = text.slice(start, i).trim();
        start = i + 1;
      }
      depth += 1;
    } else if (text[i] === '}') {
      depth -= 1;
      if (depth === 0) {
        if (!selector.startsWith('@')) rules.push({ selector, body: text.slice(start, i) });
        start = i + 1;
      }
    }
  }
  return rules;
}

function declarations(body) {
  const out = {};
  for (const match of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) out[match[1]] = match[2].trim();
  return out;
}

/** {light: {--name: '#hex'}, dark: {...}} with every var() resolved, the way the browser would */
export function readThemes(css = readFileSync(TOKENS_FILE, 'utf8')) {
  let root = {};
  let light = {};
  let dark = {};
  for (const { selector, body } of topLevelRules(css)) {
    const decls = declarations(body);
    if (selector.includes("[data-theme='dark']")) dark = { ...dark, ...decls };
    else if (selector.includes("[data-theme='light']")) light = { ...light, ...decls };
    else if (selector.includes(':root')) root = { ...root, ...decls };
  }
  const resolveAll = (map) => {
    const lookup = (name, seen = new Set()) => {
      if (seen.has(name)) throw new Error(`Circular token: ${[...seen, name].join(' -> ')}`);
      const raw = map[name];
      if (raw === undefined) return undefined;
      return raw.replace(/var\(\s*(--[\w-]+)\s*(?:,\s*([^)]+))?\)/g, (_, ref, fallback) => {
        const value = lookup(ref, new Set([...seen, name]));
        if (value === undefined && fallback === undefined) throw new Error(`${name} uses ${ref}, which is not defined`);
        return value ?? fallback.trim();
      });
    };
    return Object.fromEntries(Object.keys(map).map((name) => [name, lookup(name)]));
  };
  return { light: resolveAll({ ...root, ...light }), dark: resolveAll({ ...root, ...dark }) };
}

/** One row per pair per theme: {theme, fg, bg, fgValue, bgValue, ratio, min, pass, use} */
export function checkContrast(themes = readThemes()) {
  const rows = [];
  for (const theme of ['light', 'dark']) {
    for (const pair of CONTRAST_PAIRS) {
      const fgValue = themes[theme][pair.fg];
      const bgValue = themes[theme][pair.bg];
      if (fgValue === undefined || bgValue === undefined) {
        throw new Error(`${theme}: ${fgValue === undefined ? pair.fg : pair.bg} is not defined in tokens.css`);
      }
      const ratio = contrastRatio(fgValue, bgValue);
      rows.push({ theme, ...pair, fgValue, bgValue, ratio, pass: Math.floor(ratio * 100) / 100 >= pair.min });
    }
  }
  return rows;
}

function toMarkdown(rows) {
  const lines = [
    '# Colour contrast: every token pair, both themes',
    '',
    'Generated by `npm run contrast` from `src/styles/tokens.css` (do not edit by hand). Ratios are rounded **down**, so a pair',
    'shown as passing really passes. Minimums: **4.5:1** for text (WCAG 1.4.3), **3:1** for the parts of a control you need to',
    'see and for the focus ring (WCAG 1.4.11, 2.4.7).',
    '',
  ];
  for (const theme of ['light', 'dark']) {
    const themed = rows.filter((r) => r.theme === theme);
    const lowest = themed.reduce((low, r) => (r.ratio < low.ratio ? r : low));
    lines.push(`## ${theme === 'light' ? 'Light' : 'Dark'} theme`, '');
    lines.push(`${themed.filter((r) => r.pass).length} of ${themed.length} pairs pass. Lowest: ${formatRatio(lowest.ratio)}:1 (${lowest.use}).`, '');
    lines.push('| Used for | Foreground | Background | Ratio | Needs | Result |', '|---|---|---|---:|---:|---|');
    for (const r of themed) {
      lines.push(`| ${r.use} | \`${r.fg}\` ${r.fgValue} | \`${r.bg}\` ${r.bgValue} | ${formatRatio(r.ratio)}:1 | ${r.min}:1 | ${r.pass ? 'Pass' : '**FAIL**'} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const rows = checkContrast();
  const out = resolve(ROOT, 'docs/contrast.md');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, toMarkdown(rows));
  const failures = rows.filter((r) => !r.pass);
  for (const theme of ['light', 'dark']) {
    const themed = rows.filter((r) => r.theme === theme);
    const lowest = themed.reduce((low, r) => (r.ratio < low.ratio ? r : low));
    console.log(`${theme.padEnd(5)}  ${themed.length - themed.filter((r) => !r.pass).length}/${themed.length} pass, lowest ${formatRatio(lowest.ratio)}:1 (${lowest.use})`);
  }
  for (const f of failures) console.error(`FAIL ${f.theme}: ${f.use}: ${f.fg} on ${f.bg} = ${formatRatio(f.ratio)}:1, needs ${f.min}:1`);
  console.log(`wrote ${out.replace(`${ROOT}/`, '')}`);
  process.exit(failures.length ? 1 : 0);
}
