import { createContext, useCallback, useContext, useMemo, useState } from 'react';
import { getDataset } from '../data/generateUsers';
import { createIndex } from '../lib/query';

/**
 * DATA CONTEXT: the user dataset every screen shares, plus the small bits of cross-screen state.
 *
 *   users        the current dataset (edits applied)
 *   index        the prepared search index for `users` (built once per dataset, not per keystroke)
 *   size         how many users are generated (1,000 / 10,000 / 50,000)
 *   setSize      change it
 *   selectedId   the user chosen for the Profile form
 *   editUser(id) select a user and jump to the Profile form tab
 *   saveUser(u)  replace a user with an edited copy
 *   tab/setTab   the open tab, so any screen can send you to another one
 *
 * The dataset is generated by a seeded generator, so 10,000 users are identical on every load.
 */
const DataContext = createContext(null);
export const SIZES = [1000, 10000, 50000];
export const TABS = [
  { id: 'directory', label: 'Directory' },
  { id: 'dashboard', label: 'Dashboard' },
  { id: 'search', label: 'Search lab' },
  { id: 'profile', label: 'Profile form' },
  { id: 'methods', label: 'Methods' },
  { id: 'benchmark', label: 'Benchmark' },
];

export function DataProvider({ children, initialSize = 10000, initialTab = 'directory' }) {
  const [size, setSize] = useState(initialSize);
  const [edits, setEdits] = useState({}); // { [id]: editedUser }, kept apart so changing size is cheap
  const [selectedId, setSelectedId] = useState(1);
  const [tab, setTab] = useState(initialTab);

  const base = useMemo(() => getDataset(size), [size]);
  const users = useMemo(() => (Object.keys(edits).length ? base.map((u) => edits[u.id] ?? u) : base), [base, edits]);
  const index = useMemo(() => createIndex(users), [users]);

  const saveUser = useCallback((user) => setEdits((current) => ({ ...current, [user.id]: user })), []);
  const editUser = useCallback((id) => {
    setSelectedId(id);
    setTab('profile');
  }, []);

  const value = useMemo(
    () => ({ users, index, size, setSize, selectedId, setSelectedId, editUser, saveUser, tab, setTab }),
    [users, index, size, selectedId, editUser, saveUser, tab]
  );
  return <DataContext.Provider value={value}>{children}</DataContext.Provider>;
}

export function useData() {
  const context = useContext(DataContext);
  if (context === null) throw new Error('useData must be used inside a <DataProvider>.');
  return context;
}
